day_names = {1: "周一", 2: "周二", 3: "周三", 4: "周四", 5: "周五"}

def add_course(name, day, start, end, week_type):
    data = {
        "course_name": name,
        "day_of_week": day,
        "start_time": start + ":00",
        "end_time": end + ":00",
        "week_type": week_type,
        "color": COLORS.get(name, "#1890ff")
    }
    try:
        r = requests.post(f"{BASE_URL}/api/courses", json=data, timeout=5)
        if r.status_code == 200:
            print(f"  ✅ {name} ({day_names[day]} {start}-{end})")
            return True
        else:
            print(f"  ❌ {name} 失败：{r.status_code}")
            return False
    except Exception as e:
        print(f"  ❌ {name} 错误：{e}")
        return False

